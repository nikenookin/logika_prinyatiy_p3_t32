import 'dart:io';

void main() {
  int health = 100;
  bool hasKey = false;

  print("=== ДОБРО ПОЖАЛОВАТЬ В ТЕКСТОВЫЙ КВЕСТ ===");
  print("Вы просыпаетесь в темном бункере. Голова гудит.");
  print("Перед вами две массивные двери: [1] Левая дверь и [2] Правая дверь.");
  stdout.write("Куда вы пойдете? (Введите 1 или 2): ");

  String? choice1 = stdin.readLineSync();

  if (choice1 == "1") {
    print("\nВы заходите в тускло освещенную лабораторию.");
    print("На столе лежит стальной ключ, но в углу возится мутант!");
    print("Что вы делаете? [1] Тихо забрать ключ и уйти, [2] Напасть на мутанта.");
    stdout.write("Ваш выбор (1-2): ");

    String? choice2Left = stdin.readLineSync();

    if (choice2Left == "1") {
      hasKey = true;
      print("\nВы ловко подкрались, схватили ключ (у вас появился ключ!) и вернулись назад.");
    } else if (choice2Left == "2") {
      health -= 60;
      print("\nМутант разорвал вас! Вы потеряли много здоровья. Текущее HP: $health");
      if (health <= 0) {
        print("=== ИГРА ОКОНЧЕНА (Вы погибли) ===");
        return;
      }
    } else {
      print("\nНеверная команда. Вы растерялись, и мутант вас прогнал.");
    }

  } else if (choice1 == "2") {
    print("\nВы попадаете в длинный темный коридор с разбитыми колбами.");
    print("Ничего интересного, кромешная тьма. Вы возвращаетесь в центральный зал.");
  } else {
    print("\nНеверный ввод. Вы простояли на месте, ничего не сделав.");
  }

  print("\nВы возвращаетесь к запертому выходу из бункера.");
  print("Тяжелая дверь заблокирована. Чтобы открыть её, нужны силы и ключ доступа.");

  if (hasKey && health > 0) {
    print("\nВы применяете ключ и из последних сил толкаете тяжелую створку...");
    print("🎉 ПОБЕДА! Вы выбрались на поверхность и вдохнули свежий воздух!");
  } else {
    print("\nУ вас нет ключа или вы слишком слабы, чтобы сдвинуть засов. Вы заперты навсегда.");
    print("=== ИГРА ОКОНЧЕНА ===");
  }
}